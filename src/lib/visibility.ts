/**
 * Кой се състезава и кой само гледа.
 *
 * Единственият източник на истина за видимостта на профилите. Държи се
 * отделно от `guards.ts`, защото там въпросът е „какво му е позволено", а тук
 * — „вижда ли се от другите". Двете нарочно не съвпадат: тестовият профил може
 * всичко, което може редовният, но никой освен него не го вижда.
 *
 * SQL-вариантът е в `visibility-sql.ts` — тук не се внася drizzle, за да може
 * файлът да влиза и в клиентски компоненти.
 */

export type UserRole = 'user' | 'admin' | 'test';

/**
 * Влиза ли профилът в класирането и вижда ли се от останалите.
 *
 * Правилото е обърнато нарочно: състезател е само изричното „user". Ако утре
 * се добави нова роля, тя ще е скрита по подразбиране — по-безопасната посока,
 * отколкото случайно да изтече служебен профил в класирането.
 */
export function isCompetitor(role: UserRole): boolean {
  return role === 'user';
}

/**
 * Вижда ли зрителят конкретен профил.
 *
 * Себе си човек вижда винаги — иначе админът и тестовият профил не биха
 * намирали собствените си прогнози, а те правят прогнози като всички.
 */
export function isVisibleTo(target: { id: string; role: UserRole }, viewerId: string): boolean {
  return isCompetitor(target.role) || target.id === viewerId;
}

export const ROLE_LABEL: Record<UserRole, string> = {
  user: 'участник',
  admin: 'админ',
  test: 'тест',
};
